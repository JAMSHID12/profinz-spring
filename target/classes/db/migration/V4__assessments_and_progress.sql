-- =============================================================================
-- V4: daily/weekly tests, exams, results, syllabus progress and progress cards.
--
-- Tests, exams and progress cards follow DRAFT -> REVIEW -> PUBLISHED. Students
-- only ever see PUBLISHED rows.
-- =============================================================================

CREATE TABLE tests (
    id           BIGINT       NOT NULL AUTO_INCREMENT,
    client_id    BIGINT       NOT NULL,
    test_type    VARCHAR(20)  NOT NULL,
    title        VARCHAR(150) NOT NULL,
    batch_id     BIGINT       NOT NULL,
    subject_id   BIGINT       NOT NULL,
    test_date    DATE         NOT NULL,
    week_number  INT          NULL,
    max_marks    DECIMAL(7,2) NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    remarks      VARCHAR(500) NULL,
    published_at DATETIME(6)  NULL,
    published_by BIGINT       NULL,
    created_at   DATETIME(6)  NOT NULL,
    updated_at   DATETIME(6)  NOT NULL,
    created_by   BIGINT       NULL,
    updated_by   BIGINT       NULL,
    PRIMARY KEY (id),
    CONSTRAINT chk_tests_max_marks CHECK (max_marks > 0),
    CONSTRAINT chk_tests_week CHECK (week_number IS NULL OR week_number BETWEEN 1 AND 53),
    KEY idx_tests_batch_date (batch_id, test_date),
    KEY idx_tests_type_status (client_id, test_type, status),
    CONSTRAINT fk_tests_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_tests_batch FOREIGN KEY (batch_id) REFERENCES batches (id),
    CONSTRAINT fk_tests_subject FOREIGN KEY (subject_id) REFERENCES subjects (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE test_results (
    id             BIGINT       NOT NULL AUTO_INCREMENT,
    client_id      BIGINT       NOT NULL,
    test_id        BIGINT       NOT NULL,
    student_id     BIGINT       NOT NULL,
    marks_obtained DECIMAL(7,2) NULL,
    absent         BOOLEAN      NOT NULL DEFAULT FALSE,
    remarks        VARCHAR(255) NULL,
    created_at     DATETIME(6)  NOT NULL,
    updated_at     DATETIME(6)  NOT NULL,
    created_by     BIGINT       NULL,
    updated_by     BIGINT       NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_test_results_test_student UNIQUE (test_id, student_id),
    CONSTRAINT chk_test_results_marks CHECK (marks_obtained IS NULL OR marks_obtained >= 0),
    KEY idx_test_results_student (student_id),
    CONSTRAINT fk_test_results_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_test_results_test FOREIGN KEY (test_id) REFERENCES tests (id),
    CONSTRAINT fk_test_results_student FOREIGN KEY (student_id) REFERENCES students (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE exams (
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    client_id     BIGINT       NOT NULL,
    name          VARCHAR(150) NOT NULL,
    exam_type_id  BIGINT       NOT NULL,
    course_id     BIGINT       NOT NULL,
    batch_id      BIGINT       NOT NULL,
    subject_id    BIGINT       NOT NULL,
    exam_date     DATE         NOT NULL,
    start_time    TIME         NULL,
    end_time      TIME         NULL,
    max_marks     DECIMAL(7,2) NOT NULL,
    passing_marks DECIMAL(7,2) NOT NULL,
    faculty_id    BIGINT       NULL,
    status        VARCHAR(20)  NOT NULL,
    remarks       VARCHAR(500) NULL,
    published_at  DATETIME(6)  NULL,
    published_by  BIGINT       NULL,
    created_at    DATETIME(6)  NOT NULL,
    updated_at    DATETIME(6)  NOT NULL,
    created_by    BIGINT       NULL,
    updated_by    BIGINT       NULL,
    PRIMARY KEY (id),
    CONSTRAINT chk_exams_marks CHECK (max_marks > 0 AND passing_marks >= 0 AND passing_marks <= max_marks),
    CONSTRAINT chk_exams_times CHECK (start_time IS NULL OR end_time IS NULL OR start_time < end_time),
    KEY idx_exams_batch_date (batch_id, exam_date),
    KEY idx_exams_status (client_id, status),
    CONSTRAINT fk_exams_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_exams_exam_type FOREIGN KEY (exam_type_id) REFERENCES exam_types (id),
    CONSTRAINT fk_exams_course FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk_exams_batch FOREIGN KEY (batch_id) REFERENCES batches (id),
    CONSTRAINT fk_exams_subject FOREIGN KEY (subject_id) REFERENCES subjects (id),
    CONSTRAINT fk_exams_faculty FOREIGN KEY (faculty_id) REFERENCES faculty (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE exam_results (
    id             BIGINT       NOT NULL AUTO_INCREMENT,
    client_id      BIGINT       NOT NULL,
    exam_id        BIGINT       NOT NULL,
    student_id     BIGINT       NOT NULL,
    marks_obtained DECIMAL(7,2) NULL,
    absent         BOOLEAN      NOT NULL DEFAULT FALSE,
    grade          VARCHAR(10)  NULL,
    remarks        VARCHAR(255) NULL,
    created_at     DATETIME(6)  NOT NULL,
    updated_at     DATETIME(6)  NOT NULL,
    created_by     BIGINT       NULL,
    updated_by     BIGINT       NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_exam_results_exam_student UNIQUE (exam_id, student_id),
    CONSTRAINT chk_exam_results_marks CHECK (marks_obtained IS NULL OR marks_obtained >= 0),
    KEY idx_exam_results_student (student_id),
    CONSTRAINT fk_exam_results_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_exam_results_exam FOREIGN KEY (exam_id) REFERENCES exams (id),
    CONSTRAINT fk_exam_results_student FOREIGN KEY (student_id) REFERENCES students (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE syllabus_topics (
    id            BIGINT        NOT NULL AUTO_INCREMENT,
    client_id     BIGINT        NOT NULL,
    course_id     BIGINT        NOT NULL,
    subject_id    BIGINT        NOT NULL,
    title         VARCHAR(200)  NOT NULL,
    description   VARCHAR(1000) NULL,
    sequence_no   INT           NOT NULL,
    planned_hours DECIMAL(5,1)  NULL,
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    DATETIME(6)   NOT NULL,
    updated_at    DATETIME(6)   NOT NULL,
    created_by    BIGINT        NULL,
    updated_by    BIGINT        NULL,
    PRIMARY KEY (id),
    KEY idx_syllabus_topics_subject (subject_id, sequence_no),
    CONSTRAINT fk_syllabus_topics_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_syllabus_topics_course FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk_syllabus_topics_subject FOREIGN KEY (subject_id) REFERENCES subjects (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE syllabus_progress (
    id             BIGINT       NOT NULL AUTO_INCREMENT,
    client_id      BIGINT       NOT NULL,
    batch_id       BIGINT       NOT NULL,
    topic_id       BIGINT       NOT NULL,
    planned_date   DATE         NULL,
    completed_date DATE         NULL,
    status         VARCHAR(20)  NOT NULL,
    remarks        VARCHAR(500) NULL,
    created_at     DATETIME(6)  NOT NULL,
    updated_at     DATETIME(6)  NOT NULL,
    created_by     BIGINT       NULL,
    updated_by     BIGINT       NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_syllabus_progress_batch_topic UNIQUE (batch_id, topic_id),
    CONSTRAINT fk_syllabus_progress_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_syllabus_progress_batch FOREIGN KEY (batch_id) REFERENCES batches (id),
    CONSTRAINT fk_syllabus_progress_topic FOREIGN KEY (topic_id) REFERENCES syllabus_topics (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE progress_cards (
    id                  BIGINT        NOT NULL AUTO_INCREMENT,
    client_id           BIGINT        NOT NULL,
    student_id          BIGINT        NOT NULL,
    batch_id            BIGINT        NULL,
    title               VARCHAR(150)  NOT NULL,
    period_start        DATE          NOT NULL,
    period_end          DATE          NOT NULL,
    attendance_percentage DECIMAL(5,2) NULL,
    daily_test_average  DECIMAL(5,2)  NULL,
    weekly_test_average DECIMAL(5,2)  NULL,
    exam_average        DECIMAL(5,2)  NULL,
    performance_score   DECIMAL(5,2)  NULL,
    grade               VARCHAR(10)   NULL,
    syllabus_completion DECIMAL(5,2)  NULL,
    discipline_count    INT           NOT NULL DEFAULT 0,
    pending_fine_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    mentor_remarks      TEXT          NULL,
    status              VARCHAR(20)   NOT NULL,
    published_at        DATETIME(6)   NULL,
    published_by        BIGINT        NULL,
    created_at          DATETIME(6)   NOT NULL,
    updated_at          DATETIME(6)   NOT NULL,
    created_by          BIGINT        NULL,
    updated_by          BIGINT        NULL,
    PRIMARY KEY (id),
    CONSTRAINT chk_progress_cards_period CHECK (period_start <= period_end),
    KEY idx_progress_cards_student (student_id, status),
    CONSTRAINT fk_progress_cards_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_progress_cards_student FOREIGN KEY (student_id) REFERENCES students (id),
    CONSTRAINT fk_progress_cards_batch FOREIGN KEY (batch_id) REFERENCES batches (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE progress_card_items (
    id                 BIGINT       NOT NULL AUTO_INCREMENT,
    client_id          BIGINT       NOT NULL,
    progress_card_id   BIGINT       NOT NULL,
    subject_id         BIGINT       NULL,
    subject_name       VARCHAR(150) NOT NULL,
    test_average       DECIMAL(5,2) NULL,
    exam_average       DECIMAL(5,2) NULL,
    overall_percentage DECIMAL(5,2) NULL,
    grade              VARCHAR(10)  NULL,
    remarks            VARCHAR(500) NULL,
    display_order      INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_progress_card_items_card (progress_card_id),
    CONSTRAINT fk_progress_card_items_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_progress_card_items_card FOREIGN KEY (progress_card_id) REFERENCES progress_cards (id),
    CONSTRAINT fk_progress_card_items_subject FOREIGN KEY (subject_id) REFERENCES subjects (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
